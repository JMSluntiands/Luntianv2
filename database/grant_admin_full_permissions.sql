INSERT IGNORE INTO role_permissions (role, branch, route_name)
SELECT 'Admin', '', route_name FROM tmp_all_routes;

-- 2. Bawat admin user, lahat ng permission: global ('') + sariling branch + bawat branch na may rows na siya.
--    Kapag may branch rows ang user, iyon lang ang binabasa ng app, kaya kailangang kumpleto rin doon.
INSERT IGNORE INTO user_permissions (user_id, branch, route_name)
SELECT b.user_id, b.branch, r.route_name
FROM (
    SELECT u.id AS user_id, '' AS branch
    FROM users u
    WHERE LOWER(TRIM(u.role)) = 'admin'
    UNION
    SELECT u.id, TRIM(u.branch)
    FROM users u
    WHERE LOWER(TRIM(u.role)) = 'admin' AND TRIM(COALESCE(u.branch, '')) <> ''
    UNION
    SELECT up.user_id, up.branch
    FROM user_permissions up
    JOIN users u ON u.id = up.user_id
    WHERE LOWER(TRIM(u.role)) = 'admin' AND up.branch <> ''
) b
CROSS JOIN tmp_all_routes r;

-- 3. Admin role: bawat branch na may rows na
INSERT IGNORE INTO role_permissions (role, branch, route_name)
SELECT rb.role, rb.branch, r.route_name
FROM (SELECT DISTINCT role, branch FROM role_permissions WHERE LOWER(TRIM(role)) = 'admin' AND branch <> '') rb
CROSS JOIN tmp_all_routes r;

